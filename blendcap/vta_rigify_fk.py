PROPERTY_SPEC={}
for side in ('.L','.R'):
    for limb in ('upper_arm','thigh'):
        PROPERTY_SPEC[limb+'_parent'+side]={'IK_FK':1.,'FK_limb_follow':None}
PROPERTY_SPEC['torso']={'neck_follow':None,'head_follow':None,'torso_parent':None}


def _plain(value,rig):
    if isinstance(value,bpy.types.ID):return 'SELF' if value in (rig,rig.data) else value.name_full
    if isinstance(value,(str,int,float,bool)) or value is None:return value
    if isinstance(value,set):return tuple(sorted(value))
    try:return tuple(_plain(v,rig) for v in value)
    except TypeError:return str(value)


def _rna(owner,rig,*,exclude=()):
    result={}
    for prop in owner.bl_rna.properties:
        name=prop.identifier
        if name=='rna_type' or name in exclude or prop.is_readonly:continue
        if prop.type=='COLLECTION':continue
        result[name]=_plain(getattr(owner,name),rig)
    return result


def graph_signature(rig):
    """Authored graph only, excluding evaluated influence/driver validity."""
    constraints=[];driven={f.data_path for f in rig.animation_data.drivers} if rig.animation_data else set()
    for bone in rig.pose.bones:
        for c in bone.constraints:
            row=_rna(c,rig,exclude=('influence',) if c.path_from_id('influence') in driven else ())
            if hasattr(c,'targets'):row['targets']=[_rna(t,rig) for t in c.targets]
            constraints.append((bone.name,c.name,row))
    drivers=[]
    for label,owner in (('object',rig),('data',rig.data)):
        for f in owner.animation_data.drivers if owner.animation_data else ():
            drivers.append((label,f.data_path,f.array_index,f.mute,f.driver.type,f.driver.expression,f.driver.use_self,
                [(v.name,v.type,[_rna(t,rig) for t in v.targets]) for v in f.driver.variables],
                [_rna(m,rig) for m in f.modifiers]))
    return hashlib.sha256(json.dumps((constraints,drivers),sort_keys=True).encode()).hexdigest()


def _path_bones(path):return re.findall(r'pose\.bones\[("(?:[^"\\]|\\.)*")\]',path)


def _standard_driver(driver):
    return driver.type in ('SUM','AVERAGE','MIN','MAX') or (driver.type=='SCRIPTED' and driver.is_simple_expression)


def body_topology(rig,prefix):
    """Topology/constraint shapes, not proportions, rest roll or widget data."""
    names={prefix+n for n in (*CONTROLS.values(),*OBSERVATIONS.values(),'torso','hips','chest','root')}
    pending=list(names)
    while pending:
        name=pending.pop();bone=rig.pose.bones.get(name)
        if bone is None:raise ValueError('Missing required Rigify body bone: '+name)
        refs=[bone.parent.name] if bone.parent else []
        for c in bone.constraints:
            if getattr(c,'subtarget',''):refs.append(c.subtarget)
            if hasattr(c,'targets'):refs.extend(t.subtarget for t in c.targets if t.subtarget)
        for ref in refs:
            if ref not in names:names.add(ref);pending.append(ref)
    rows=[]
    strip=lambda name:name[len(prefix):] if prefix and name.startswith(prefix) else name
    for name in sorted(names):
        b=rig.pose.bones[name];d=b.bone
        constraints=[]
        for c in b.constraints:
            constraints.append((c.type,strip(getattr(c,'subtarget','')),getattr(c,'owner_space',''),
                getattr(c,'target_space',''),getattr(c,'mix_mode',''),getattr(c,'use_offset',False),
                [strip(t.subtarget) for t in c.targets] if hasattr(c,'targets') else []))
        rows.append((strip(name),strip(b.parent.name) if b.parent else None,d.inherit_scale,
                     d.use_inherit_rotation,d.use_local_location,constraints))
    return hashlib.sha256(json.dumps(rows,sort_keys=True).encode()).hexdigest()


# Stock Blender 5.2 human, body dependency closure only (no face/finger layout).
# Generated by the local reproducible topology proof, not a metric rest-pose hash.
STANDARD_BODY_TOPOLOGY='cf7bbc5e2ccbafa4244ebd81da164aa72ac1aef6e563c9cb6688908a2f96e3e3'


def validate(rig,match):
    prefix=match.prefix
    if not isinstance(rig.data.get('rig_id'),str) or not rig.data.get('rig_id'):
        raise ValueError('Choose an already-generated standard Rigify rig, not a metarig.')
    data_anim=rig.data.animation_data
    if data_anim and (data_anim.action or data_anim.nla_tracks or data_anim.use_tweak_mode):
        raise ValueError('Rigify armature-data Actions/NLA are unsupported.')
    if body_topology(rig,prefix)!=STANDARD_BODY_TOPOLOGY:
        raise ValueError('Customized or unsupported Rigify body structure; use a standard generated human rig.')
    for name,props in PROPERTY_SPEC.items():
        bone=rig.pose.bones.get(prefix+name)
        for key in props:
            value=bone.get(key) if bone else None
            if not isinstance(value,(int,float)) or not math.isfinite(value):
                raise ValueError('Missing/invalid standard Rigify body property: '+name)
    for name in match.mapping.values():
        bone=rig.pose.bones[name]
        if (bone.constraints or bone.rotation_mode not in ('QUATERNION','XYZ','XZY','YXZ','YZX','ZXY','ZYX')
                or any(abs(v-1)>1e-5 for v in bone.scale)):
            raise ValueError('Unsupported Rigify FK control state: '+name)
    if not rig.animation_data or not rig.animation_data.drivers:raise ValueError('Rigify generated drivers are missing.')
    for f in rig.animation_data.drivers:
        if not f.data_path.startswith('pose.bones[') or not _standard_driver(f.driver):
            raise ValueError('Unsupported Rigify driver customization.')
        for variable in f.driver.variables:
            if any(t.id not in (None,rig,rig.data) for t in variable.targets):
                raise ValueError('Rigify body drivers must not depend on another object.')
        if any(json.loads(n) in match.mapping.values() for n in _path_bones(f.data_path)):
            raise ValueError('Driven Rigify FK controls are unsupported.')
    for f in data_anim.drivers if data_anim else ():
        if not re.fullmatch(r'bones\["(?:[^"\\]|\\.)*"\]\.bbone_ease(?:in|out)',f.data_path) or not _standard_driver(f.driver):
            raise ValueError('Unsupported Rigify armature-data driver.')
        if any(t.id not in (None,rig,rig.data) for v in f.driver.variables for t in v.targets):
            raise ValueError('External Rigify B-bone driver dependency is unsupported.')
    for bone in rig.pose.bones:
        for c in bone.constraints:
            if getattr(c,'target',None) not in (None,rig):raise ValueError('External Rigify constraint dependency is unsupported.')
            if hasattr(c,'targets') and any(t.target not in (None,rig) for t in c.targets):
                raise ValueError('External Rigify parent dependency is unsupported.')


class RigifyFk:
    def __init__(self,target,match,fingers=None):
        self.match=match;self.prefix=match.prefix;self.graph=graph_signature(target)
        self.owned=set(match.mapping.values())|{self.prefix+n for n in ('torso','hips','chest','root')}
        self.observations={s:self.prefix+n for s,n in OBSERVATIONS.items() if s in match.mapping}
        self.controls={**match.mapping,**(fingers or {})}
        for semantic,name in (fingers or {}).items():
            self.owned.add(name);self.observations[semantic]=self.prefix+'DEF-'+name[len(self.prefix):]
            stem,_segment,side=name[len(self.prefix):].split('.')
            self.owned.add(self.prefix+stem+'.01_master.'+side)
            tip=self.prefix+stem+'.01.'+side+'.001'
            if tip in target.pose.bones:self.owned.add(tip)
        self.reference={}
        for name,props in PROPERTY_SPEC.items():
            self.reference[self.prefix+name]={key:target.pose.bones[self.prefix+name][key] for key in props}
        self.before={name:dict(props) for name,props in self.reference.items()}
        old=target.animation_data.action if target.animation_data else None
        if old and old.get('vta_rigify_reference'):
            reference=json.loads(old['vta_rigify_reference'])
            if set(reference)!=set(self.reference) or any(set(reference[n])!=set(self.reference[n]) for n in reference):
                raise ValueError('Invalid Rigify reference receipt.')
            if any(not isinstance(v,(int,float)) or not math.isfinite(v) for props in reference.values() for v in props.values()):
                raise ValueError('Invalid Rigify reference value.')
            self.reference=reference
        self.values={name:{key:(PROPERTY_SPEC[name[len(self.prefix):]][key]
            if PROPERTY_SPEC[name[len(self.prefix):]][key] is not None else value) for key,value in props.items()}
            for name,props in self.reference.items()}

    def owns_property(self,owner,name):
        return isinstance(owner,bpy.types.PoseBone) and owner.name in self.values and name in self.values[owner.name]

    def prepare(self,stage):
        for name,props in self.values.items():
            for key,value in props.items():stage.pose.bones[name][key]=value
        stage.update_tag()

    def isolate_data_drivers(self,stage,target):
        for owner in (stage,stage.data):
            for f in owner.animation_data.drivers if owner.animation_data else ():
                for variable in f.driver.variables:
                    for t in variable.targets:
                        if t.id==target:t.id=stage
                        elif t.id==target.data:t.id=stage.data

    def restore(self,target):
        for name,props in self.before.items():
            for key,value in props.items():target.pose.bones[name][key]=value
        target.update_tag()

    def property_keys(self,stage,frames):
        for frame in frames:
            for name,props in self.values.items():
                for key,value in props.items():
                    bone=stage.pose.bones[name];bone[key]=value;bone.keyframe_insert('['+json.dumps(key)+']',frame=frame)

    def correct_pelvis(self,stage,sample):
        """Only normal torso location channels; no DEF pose assignments."""
        self.prepare(stage);stage.update_tag();bpy.context.view_layer.update()
        ev=stage.evaluated_get(bpy.context.evaluated_depsgraph_get())
        got=(ev.matrix_world@ev.pose.bones[self.observations['hips']].matrix).translation
        wanted=Vector(sample['poses']['hips'][i][3] for i in range(3))
        torso=stage.pose.bones[self.prefix+'torso'];matrix=torso.matrix.copy()
        matrix.translation+=stage.matrix_world.inverted().to_3x3()@(wanted-got)
        torso.matrix=matrix;torso.keyframe_insert('location',frame=sample['frame'])

    def finish_action(self,action):
        action['vta_rigify_reference']=json.dumps(self.reference)

    def validate_deform(self,ev,sample,offsets):
        for semantic,name in self.observations.items():
            if semantic not in sample['poses']:continue
            got=ev.matrix_world@ev.pose.bones[name].matrix
            control=ev.matrix_world@ev.pose.bones[self.controls[semantic]].matrix
            if not all(math.isfinite(v) for row in got for v in row):raise ValueError('Nonfinite Rigify deform pose: '+name)
            # Bendy spine segments introduce small tangent differences. A broad
            # refusal bound catches disconnected/flipped control/deform paths.
            rest_control=ev.data.bones[self.controls[semantic]].matrix_local.to_quaternion()
            rest_deform=ev.data.bones[name].matrix_local.to_quaternion()
            expected=control.to_quaternion()@rest_control.inverted()@rest_deform
            # Rigify distributes roll along split B-bones. Validate direction
            # and physical joint attachment, not equality to an unsplit FK roll.
            direction=got.to_3x3().col[1].normalized()
            expected_direction=expected.to_matrix().col[1].normalized()
            if direction.angle(expected_direction)>math.radians(12):raise ValueError('Rigify deform direction diverged: '+name)
            org_name=name.replace(self.prefix+'DEF-',self.prefix+'ORG-',1)
            if org_name in ev.pose.bones:
                org=ev.matrix_world@ev.pose.bones[org_name].matrix
                if (got.translation-org.translation).length>1e-4:raise ValueError('Rigify deform joint detached: '+name)
        pelvis=ev.matrix_world@ev.pose.bones[self.observations['hips']].matrix
        if (pelvis.translation-Vector(sample['poses']['hips'][i][3] for i in range(3))).length>1e-4:
            raise ValueError('Rigify evaluated pelvis alignment failed.')
